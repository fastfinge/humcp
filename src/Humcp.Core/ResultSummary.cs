using System.Text;
using Humcp.Schema;

namespace Humcp.Core;

/// <summary>
/// A summary of a long result, by the local model, on request (ROADMAP §11, Phase 11): what is sent
/// to it, the request it is given, and what humcp says about what comes back.
/// </summary>
public static class ResultSummary
{
    /// <summary>
    /// Below this a result is not offered a summary: about a screen of text, which takes less time to
    /// read than a summary takes to make.
    /// </summary>
    public const int WorthSummarising = 1500;

    /// <summary>
    /// What is sent at most — about 10,000 tokens of prose, fewer of JSON. The spike's 10.4k-token
    /// result took two to four minutes on the processor (v2-llm-spike §4); past this a summary is a
    /// wait nobody would choose, so the rest is left out and the summary says so.
    /// </summary>
    public const int MaxCharacters = 32_000;

    public const string Summarising =
        "Summarising it with the local model. A long result can take a few minutes on the processor; the summary will appear here.";

    public const string Offer =
        "Not summarised. Control plus M, or Summarise below, asks the local model on this computer for a summary of the whole result.";

    public const string NotDownloaded =
        "Not summarised. File, Local model downloads a model that can summarise results on this computer.";

    /// <summary>
    /// The result as the model reads it: every text part, and structured content where it says
    /// something the text does not. Pictures and links are not text and are left out.
    /// </summary>
    public static string Source(ToolCallOutcome outcome)
    {
        ArgumentNullException.ThrowIfNull(outcome);

        var text = new StringBuilder();

        foreach (var block in outcome.Blocks)
        {
            var part = block switch
            {
                TextResultBlock t => t.Text,
                ResourceTextResultBlock r => r.Text,
                _ => null,
            };

            if (string.IsNullOrWhiteSpace(part)) continue;
            if (text.Length > 0) text.Append("\n\n");
            text.Append(part);
        }

        if (outcome.HasOwnStructuredContent && outcome.Structured is { } structured)
        {
            if (text.Length > 0) text.Append("\n\n");
            text.Append(structured.GetRawText());
        }

        return text.ToString();
    }

    public static bool IsWorthSummarising(ToolCallOutcome outcome) => Source(outcome).Length >= WorthSummarising;

    /// <summary>
    /// The request: the spike's (v2-llm-spike §4.1), under which every claim the 4B model made traced to
    /// its source. Returns whether the result had to be cut to fit.
    /// </summary>
    public static (string Request, bool Cut) Request(string toolName, ToolCallOutcome outcome)
    {
        var source = Source(outcome);
        var cut = source.Length > MaxCharacters;
        if (cut) source = source[..MaxCharacters];

        var request =
            $"A tool called {TextSanitizer.Clean(toolName, TextSanitizer.NameLength)} returned the result below. " +
            "Summarise it in plain sentences for someone listening with a screen reader: lead with what matters most, " +
            "give the key facts and numbers, and keep it under 150 words. Do not add anything the result does not contain." +
            $"\n\nResult:\n{source}";

        return (request, cut);
    }

    /// <summary>The summary as it is shown: labelled first, and saying so when it was made from part of the result.</summary>
    public static string Generated(string summary, bool cut)
        => GeneratedText.Label(summary) + (cut
            ? $" It was made from the first {MaxCharacters:N0} characters of the result, which is longer."
            : "");

    public static string Ready(string where)
        => $"The summary is ready, {where}. It is generated, so it can be wrong.";

    public static string Failed(string reason)
        => $"The result could not be summarised. {TextSanitizer.Clean(reason, TextSanitizer.HelpLength)}";
}

/// <summary>
/// The one label every piece of model-written text carries (§11.0): "Generated by the local model,
/// and it can be wrong:", before a word of it, so it never arrives with the authority of something a
/// server sent.
/// </summary>
public static class GeneratedText
{
    /// <summary>Model text longer than this is cut: what was asked for is far shorter.</summary>
    public const int MaxLength = 2000;

    public const string Prefix = "Generated by the local model, and it can be wrong: ";

    public static string Label(string text) => Prefix + TextSanitizer.Clean(text, MaxLength);
}
