using System.Text;

namespace Humcp.Schema.Tests;

/// <summary>
/// One checked-in transcript per harvested server, showing what the engine makes of every one of
/// its tools (ROADMAP §9). Their job is not to be right — nobody hand-computed them — but to make
/// any change in tiering visible in a diff, so a refactor that quietly demotes forty fields to a
/// JSON editor cannot pass as green.
/// </summary>
/// <remarks>
/// Regenerate with <c>HUMCP_UPDATE_GOLDEN=1 dotnet test tests/Humcp.Schema.Tests</c>, then read the
/// diff. The regeneration deliberately still fails: a golden file that rewrites itself on the way
/// past is not a test of anything.
/// </remarks>
public class GoldenTests
{
    [Theory]
    [MemberData(nameof(Servers))]
    public void The_engine_still_says_what_it_said_last_time(string server)
    {
        var actual = Render(server);
        var path = Path.Combine(Corpus.GoldenDirectory, server + ".txt");

        if (Corpus.UpdatingGolden)
        {
            Directory.CreateDirectory(Corpus.GoldenDirectory);
            File.WriteAllText(path, actual);
            Assert.Fail($"Rewrote {path}. Read the diff, then run again without HUMCP_UPDATE_GOLDEN.");
        }

        Assert.True(File.Exists(path),
            $"No golden file for {server}. Generate it with HUMCP_UPDATE_GOLDEN=1 and review the result.");

        Assert.Equal(Normalise(File.ReadAllText(path)), Normalise(actual));
    }

    public static TheoryData<string> Servers()
    {
        var data = new TheoryData<string>();
        foreach (var server in Corpus.Entries.Select(e => e.Server).Distinct().Order(StringComparer.Ordinal))
            data.Add(server);

        return data;
    }

    private static string Render(string server)
    {
        var sb = new StringBuilder();
        var entries = Corpus.Entries.Where(e => e.Server == server).ToList();

        sb.Append("# ").Append(server).Append(" — ").Append(entries[0].Package).AppendLine();
        sb.AppendLine("# Generated by Humcp.Schema.Tests. Do not hand-edit; see GoldenTests.");
        sb.AppendLine();

        foreach (var entry in entries.OrderBy(e => e.Tool, StringComparer.Ordinal))
        {
            sb.Append(FormReport.Render(entry.Tool, FormBuilder.Build(entry.InputSchema)));
            sb.AppendLine();
        }

        return sb.ToString();
    }

    /// <summary>Line endings are a property of whoever checked the file out, not of the engine.</summary>
    private static string Normalise(string text) => text.ReplaceLineEndings("\n").TrimEnd('\n');
}
