using System.Text.Json;

namespace Humcp.Schema.Tests;

/// <summary>
/// One harvested tool, exactly as its server published it.
/// </summary>
public sealed record CorpusEntry(
    string Server,
    string Package,
    string Tool,
    string? Title,
    string? Description,
    JsonElement InputSchema,
    JsonElement? OutputSchema)
{
    /// <summary>What a failing test prints, and how a theory names its cases.</summary>
    public override string ToString() => Key;

    /// <summary>Stable identity, and the key a theory passes around instead of the entry itself.</summary>
    public string Key => $"{Server}/{Tool}";
}

/// <summary>
/// The schema corpus (ROADMAP §9): real <c>inputSchema</c> documents from real MCP servers, none of
/// them written by us, regenerated by <c>tools/Humcp.Harvester</c>.
/// </summary>
/// <remarks>
/// This is the highest-value test asset in the project, and its value is entirely that nobody here
/// chose what is in it. Tier coverage measured against schemas we invented would measure our
/// imagination.
/// </remarks>
public static class Corpus
{
    private static readonly Lazy<IReadOnlyList<CorpusEntry>> Loaded = new(Load);

    /// <summary>Every harvested tool, ordered so a failure names the same one every run.</summary>
    public static IReadOnlyList<CorpusEntry> Entries => Loaded.Value;

    /// <summary>
    /// The corpus as theory data. Keys rather than entries: a <see cref="JsonElement"/> is not
    /// serialisable, and xunit wants theory arguments it can write down so a single case can be
    /// re-run on its own.
    /// </summary>
    public static TheoryData<string> Keys()
    {
        var data = new TheoryData<string>();
        foreach (var entry in Entries) data.Add(entry.Key);
        return data;
    }

    public static CorpusEntry Get(string key) =>
        Entries.FirstOrDefault(e => e.Key == key)
        ?? throw new InvalidOperationException($"No corpus entry {key}.");

    public static string Directory => Path.Combine(RepoRoot(), "tests", "fixtures", "schemas");

    public static string GoldenDirectory => Path.Combine(RepoRoot(), "tests", "fixtures", "golden");

    /// <summary>
    /// Set <c>HUMCP_UPDATE_GOLDEN=1</c> to rewrite the golden files instead of comparing against
    /// them. The rewrite still fails the test, so a regeneration can never pass unreviewed.
    /// </summary>
    public static bool UpdatingGolden =>
        Environment.GetEnvironmentVariable("HUMCP_UPDATE_GOLDEN") is "1" or "true";

    private static IReadOnlyList<CorpusEntry> Load()
    {
        var entries = new List<CorpusEntry>();

        foreach (var file in System.IO.Directory
                     .EnumerateFiles(Directory, "*.json", SearchOption.AllDirectories)
                     .Where(f => Path.GetFileName(f) != "manifest.json")
                     .OrderBy(f => f, StringComparer.Ordinal))
        {
            using var document = JsonDocument.Parse(File.ReadAllText(file));
            var root = document.RootElement;

            entries.Add(new CorpusEntry(
                Server: String(root, "server") ?? Path.GetFileName(Path.GetDirectoryName(file))!,
                Package: String(root, "package") ?? "",
                Tool: String(root, "name") ?? Path.GetFileNameWithoutExtension(file),
                Title: String(root, "title"),
                Description: String(root, "description"),
                InputSchema: root.GetProperty("inputSchema").Clone(),
                OutputSchema: root.TryGetProperty("outputSchema", out var output)
                              && output.ValueKind != JsonValueKind.Null
                    ? output.Clone()
                    : null));
        }

        if (entries.Count == 0)
            throw new InvalidOperationException(
                $"The corpus at {Directory} is empty. Run: dotnet run --project tools/Humcp.Harvester");

        return entries;
    }

    private static string? String(JsonElement node, string property) =>
        node.TryGetProperty(property, out var value) && value.ValueKind == JsonValueKind.String
            ? value.GetString()
            : null;

    private static string RepoRoot()
    {
        for (var directory = new DirectoryInfo(AppContext.BaseDirectory);
             directory is not null;
             directory = directory.Parent)
        {
            if (File.Exists(Path.Combine(directory.FullName, "Humcp.slnx"))) return directory.FullName;
        }

        throw new InvalidOperationException("Could not find Humcp.slnx above the test assembly.");
    }
}
