namespace Humcp.Core.Tests;

/// <summary>
/// A generated description is labelled as generated wherever it is read or heard (ROADMAP §11.0,
/// Phase 10): the user cannot check it against the picture.
/// </summary>
public class ImageDescriptionTests
{
    [Fact]
    public void The_description_says_what_it_is_before_a_word_of_it()
        => Assert.StartsWith("Generated by the local model, and it can be wrong: A bar chart",
            ImageDescription.Generated("A bar chart of rainfall."));

    [Fact]
    public void The_announcement_says_it_is_generated_and_where_it_is()
    {
        var said = ImageDescription.Ready("an image, PNG, 45 KB");

        Assert.Contains("an image, PNG, 45 KB", said);
        Assert.Contains("generated", said);
        Assert.Contains("in the result", said);
    }

    [Fact]
    public void Generated_text_gets_the_hygiene_server_text_does()
    {
        var said = ImageDescription.Generated("A chart\u0007 with\n\n  a bell" + new string('x', 5000));

        Assert.DoesNotContain('\u0007', said);
        Assert.DoesNotContain('\n', said);
        Assert.True(said.Length < ImageDescription.MaxLength + 100);
    }

    [Fact]
    public void Without_a_model_it_says_where_to_get_one()
        => Assert.Contains("File, Local model", ImageDescription.NotDownloaded);
}
